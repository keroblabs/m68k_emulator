def generate_irq_handlers():
    """
    Generates a C file with a list of interrupt handler functions.
    
    The functions are named irq_n<n> where n goes from 0 to 7.
    They call intr_vector_list[<m>](), where m goes from 24 to 31.
    """
    
    filename = "../boot/irq_handlers.c"
    
    with open(filename, 'w') as f:
        f.write("/*\n")
        f.write(" * This file was automatically generated by a Python script.\n")
        f.write(" * Do not modify manually.\n")
        f.write(" */\n\n")
        
        f.write("#include \"irq_handlers.h\"\n\n")
        
        # You may need to declare or define `intr_vector_list` and its type
        f.write("static intr_hdl_t intr_vector_list[256];\n\n")

        f.write("static void unused_vector(void) { }\n\n")

        f.write("void intr_handler_init(void) {\n")
        f.write("    for(int i = 0; i < 256; i++) {\n")
        f.write("        intr_vector_list[i] = unused_vector;\n")
        f.write("    }\n")
        f.write("}\n\n")

        f.write("void intr_handler_set(uint8_t index, intr_hdl_t handler) {\n")
        f.write("    intr_vector_list[index] = (intr_hdl_t)handler;\n")
        f.write("}\n\n")

        for n in range(8):
            m = n + 24
            f.write(f"void irq_n{n}(void) {{")
            #f.write(f"void __attribute__((section(\"handlers_c\"))) irq_n{n}(void) {{")
            f.write(f"    intr_vector_list[{m}](); ")
            f.write("}\n")
        f.write("\n")

        for n in range(16):
            m = n + 32
            f.write(f"void trap_n{n}(void) {{")
            #f.write(f"void __attribute__((section(\"handlers_c\"))) trap_n{n}(void) {{")
            f.write(f"    intr_vector_list[{m}](); ")
            f.write("}\n")
        f.write("\n")

        for n in range(16):
            m = n + 64
            f.write(f"void user_n{n}(void) {{")
            #f.write(f"void __attribute__((section(\"handlers_c\"))) user_n{n}(void) {{")
            f.write(f"    intr_vector_list[{m}](); ")
            f.write("}\n")
        f.write("\n")

    print(f"Successfully generated {filename}")

if __name__ == "__main__":
    generate_irq_handlers()
